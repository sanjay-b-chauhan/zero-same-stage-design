/* Writes words.ts: her real word timings per chapter, read from the Whisper transcripts that tools/make_takes.mjs cached
   for the exact kickoff takes (keyed by file and size, so a new take means a new transcript). Run after any retake:
   node flow/room/film/make_words.mjs */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '../../..');
const hash = (s) => { let h = 5381; for (let i = 0; i < s.length; i++) h = (h * 33 + s.charCodeAt(i)) >>> 0; return h.toString(36); };
const out = {};
for (const p of ['spotify', 'amazon']) {
  const run = JSON.parse(fs.readFileSync(path.join(ROOT, `data/run_${p}.json`), 'utf8'));
  out[p] = run.lines.segments.map((s) => {
    const mp3 = path.join(ROOT, s.segment_combined_audio_url);
    const json = path.join(ROOT, 'tools/.wav/whisper', hash(mp3 + fs.statSync(mp3).size), 'transcript.json');
    if (!fs.existsSync(json)) { console.error('no transcript for', mp3, 'run WORDS=1 node tools/make_takes.mjs first'); process.exit(1); }
    const raw = JSON.parse(fs.readFileSync(json, 'utf8'));
    const list = Array.isArray(raw) ? raw : raw.words || [];
    return list.map((w) => [Math.round(+w.start * 100) / 100, String(w.text ?? w.word ?? '').trim()]);
  });
}
const body = `/* Generated by make_words.mjs from the Whisper transcripts of the real kickoff takes. Do not edit by hand. */
import type { ProjectId } from '../../types';

export type Word = [number, string];
export const WORDS: Record<ProjectId, Word[][]> = ${JSON.stringify(out)};
`;
fs.writeFileSync(path.join(import.meta.dirname, 'words.ts'), body);
console.log('words.ts', Object.entries(out).map(([k, v]) => `${k} ${v.map((c) => c.length).join('/')}`).join(', '));
